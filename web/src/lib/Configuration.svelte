<script lang="ts">
  import { untrack } from 'svelte';
  import type { Config } from './types';
  import {
    configurationError,
    conversationCount,
    loopixFields,
    outageFields,
    pollingFields,
    prepareConfig,
    storageFields,
    transportFields,
    type NumericField,
  } from './configuration';

  let {
    defaults,
    create,
    busy,
  }: {
    defaults: Config;
    create: (cfg: Config) => Promise<unknown>;
    busy: boolean;
  } = $props();
  let cfg = $state<Config>(untrack(() => JSON.parse(JSON.stringify(defaults))));
  let submitting = $state(false);
  let error = $state('');
  let receivers = $derived(
    Array.from(
      { length: Math.max(0, Math.min(10, cfg.receiver_count || 0)) },
      (_, i) => `receiver-${i + 1}`,
    ),
  );
  let conversations = $derived(conversationCount(cfg));
  let transmissions = $derived(conversations * cfg.exchanges * 2);

  async function submit(event: SubmitEvent) {
    event.preventDefault();
    if (busy || submitting) return;
    const ready = prepareConfig($state.snapshot(cfg));
    error = configurationError(ready);
    if (error) return;
    submitting = true;
    try {
      await create(ready);
    } catch (cause) {
      error =
        cause instanceof Error
          ? cause.message
          : 'The backend could not create the simulation.';
    } finally {
      submitting = false;
    }
  }
</script>

{#snippet numbers(fields: NumericField[])}
  <div class="fields">
    {#each fields as [key, label, min, max, rule] (key)}
      <label
        >{label}<input
          type="number"
          {min}
          {max}
          step={rule === 'positive' || rule === 'decimal' ? 'any' : 1}
          required
          bind:value={cfg[key]}
        /></label
      >
    {/each}
  </div>
{/snippet}

<form
  onsubmit={submit}
  aria-label="Simulation configuration"
  class="configuration"
>
  <fieldset disabled={busy || submitting} class="shell">
    <section>
      <h2>Network setup</h2>
      <div class="fields">
        <label
          >Senders<input
            type="number"
            min="1"
            max="10"
            step="1"
            required
            bind:value={cfg.sender_count}
          /></label
        >
        <label
          >Receivers<input
            type="number"
            min="1"
            max="10"
            step="1"
            required
            bind:value={cfg.receiver_count}
          /></label
        >
        <label
          >{cfg.randomise_count ? 'Minimum mix nodes' : 'Mix nodes'}<input
            type="number"
            min="10"
            max="20"
            step="1"
            required
            bind:value={cfg.min_nodes}
          /></label
        >
        {#if cfg.randomise_count}<label
            >Maximum mix nodes<input
              type="number"
              min="10"
              max="20"
              step="1"
              required
              bind:value={cfg.max_nodes}
            /></label
          >{/if}
      </div>
      <label class="tick"
        ><input type="checkbox" bind:checked={cfg.randomise_count} />Randomise
        mix node count</label
      >
    </section>
    <section>
      <h2>Conversations</h2>
      <div class="fields">
        <label
          >Pairing strategy<select bind:value={cfg.pairing_strategy}>
            <option value="all_to_one">All senders to one receiver</option
            ><option value="one_to_all">One sender to all receivers</option>
            <option value="one_to_one_pairs">One-to-one pairs</option><option
              value="random_pairs">Random distinct pairs</option
            >
          </select></label
        >
        {#if cfg.pairing_strategy === 'random_pairs'}
          <label
            >Random pair count<input
              type="number"
              min="1"
              max={cfg.sender_count * cfg.receiver_count}
              step="1"
              required
              bind:value={cfg.pair_count}
            /></label
          >
        {/if}
        <label
          >Exchanges per conversation<input
            type="number"
            min="1"
            max="10"
            step="1"
            required
            bind:value={cfg.exchanges}
          /></label
        >
      </div>
      <p class="estimate">
        {conversations || 0}
        {conversations === 1 ? 'conversation' : 'conversations'} ·
        <strong>{transmissions || 0} transmissions</strong> including replies
      </p>
    </section>
    <section>
      <h2>Run settings</h2>
      <div class="fields">
        <label
          >Random seed<input
            type="number"
            min="0"
            max={Number.MAX_SAFE_INTEGER}
            step="1"
            placeholder="Generated by Python"
            bind:value={cfg.random_seed}
          /></label
        >
        <label
          >Playback delay (ms)<input
            type="number"
            min="1"
            max="2000"
            required
            bind:value={cfg.step_delay_ms}
          /></label
        >
        <label
          >Node availability<select bind:value={cfg.pattern}>
            <option value="always_online">Always online</option><option
              value="always_offline">Always offline</option
            >
            <option value="random">Random outages</option><option value="bursty"
              >Bursty outages</option
            ><option value="scheduled">Scheduled outages</option>
          </select></label
        >
      </div>
      {#if cfg.pattern === 'scheduled'}
        <div class="schedule">
          <h3>Scheduled outages</h3>
          {#each cfg.scheduled_outages as row, index (row)}
            <div class="outage">
              <label
                >Node ID<input
                  required
                  bind:value={row.node_id}
                  placeholder="mix-1"
                /></label
              >
              <label
                >Start (ms)<input
                  type="number"
                  min="0"
                  step="1"
                  required
                  bind:value={row.start_ms}
                /></label
              >
              <label
                >Duration (ms)<input
                  type="number"
                  min="0"
                  step="1"
                  required
                  bind:value={row.duration_ms}
                /></label
              >
              <button
                class="secondary"
                type="button"
                aria-label={`Remove outage ${index + 1}`}
                onclick={() => cfg.scheduled_outages.splice(index, 1)}
                >Remove</button
              >
            </div>
          {/each}
          <button
            class="secondary"
            type="button"
            onclick={() =>
              cfg.scheduled_outages.push({
                node_id: '',
                start_ms: 0,
                duration_ms: 1000,
              })}>Add outage</button
          >
        </div>
      {/if}
      <label class="tick"
        ><input type="checkbox" bind:checked={cfg.polling_enabled} />Enable
        receiver polling</label
      >
    </section>
    <details>
      <summary>Advanced settings</summary>
      <div class="advanced">
        <h3>Receiver polling</h3>
        {@render numbers(pollingFields)}
        <div class="fields">
          {#each receivers as uid (uid)}
            <label
              >{uid}<select
                aria-label={`Polling override for ${uid}`}
                value={cfg.polling_overrides[uid] === undefined
                  ? ''
                  : String(cfg.polling_overrides[uid])}
                onchange={(event) => {
                  const choice = event.currentTarget.value;
                  if (choice === '') delete cfg.polling_overrides[uid];
                  else cfg.polling_overrides[uid] = choice === 'true';
                }}
              >
                <option value="">Use polling default</option><option
                  value="true">Enabled</option
                ><option value="false">Disabled</option>
              </select></label
            >
          {/each}
        </div>
        <h3>DHT and storage</h3>
        {@render numbers(storageFields)}
        <h3>Path timing and retries</h3>
        {@render numbers(transportFields)}
        <h3>Loopix traffic parameters</h3>
        {@render numbers(loopixFields)}
        <h3>Outage parameters</h3>
        {@render numbers(outageFields)}
      </div>
    </details>
    {#if error}<p role="alert">{error}</p>{/if}
    <div class="actions">
      <button class="primary" type="submit"
        >{submitting ? 'Creating…' : 'Create simulation'}</button
      >
    </div>
  </fieldset>
</form>

